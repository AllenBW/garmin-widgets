#!/usr/bin/env python3
"""Generate apps/lockup/source/Digits.mc: Lockup's own block numerals.

A digit is a block a thousand units tall, with slits cut out of it; its width
is a share of the row's and its height the row's. Weights differ only in how
thick the block's strokes are. `glyph` is also what designs/preview_lockup.py
draws, so the preview and the watch share one set of digits.

    python3 -I designs/gen_lockup.py

Regenerate rather than edit the output.
"""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "apps/lockup/source/Digits.mc"
WEIGHTS = {"BLACK": (0.36, 0.25), "REGULAR": (0.23, 0.16)}   # stem and bar thickness, as shares of the block
CHARS = "0123456789:/°-%"
E = 0.03                                                     # a cut runs this far past the block, so no sliver is left
SLASH = (0, 1, 0.22, 1, 0.50, 0, 0.28, 0)                    # the slash's four corners
PERCENT = (0.04, 1, 0.24, 1, 0.76, 0, 0.56, 0)               # and the percent sign's
SLANTS = {"/": SLASH, "%": PERCENT}                          # the characters drawn with one


def glyph(ch, weight):
    """(width, fills, cuts), rectangles as (u0, v0, u1, v1) in a block 1 tall"""
    tx, ty = WEIGHTS[weight]
    s = (1 - 3 * ty) / 2
    up = (ty, ty + s)
    lo = (1 - ty - s, 1 - ty)
    bar0, bar1 = ty + s, ty + s + ty
    left, right = tx, 1 - tx
    box = [(0, 0, 1, 1)]
    open_l = lambda v: (-E, v[0], right, v[1])
    open_r = lambda v: (left, v[0], 1 + E, v[1])
    hole = lambda v: (left, v[0], right, v[1])
    if ch == "1":
        w = 0.74
        st = max(0.22, tx * 0.92)
        l = (w - st) / 2
        # The flag's corner overlaps the cut below it, so that no edge is left between them in standby
        return (w, [(0, 0, w, 1)], [(-E, ty * 0.8, l, 1 - ty * 0.8), (l + st, -E, w + E, 1 - ty * 0.8),
                                    (-E, -E, l * 0.35, ty * 0.8 + 0.02)])
    table = {
        "0": (1, box, [(left, ty, right, 1 - ty)]),
        "2": (1, box, [open_l(up), open_r(lo)]),
        "3": (1, box, [open_l(up), open_l(lo)]),
        "4": (1, box, [(left, -E, right, bar0), (-E, bar1, right, 1 + E)]),
        "5": (1, box, [open_r(up), open_l(lo)]),
        "6": (1, box, [open_r(up), hole(lo)]),
        "7": (1, box, [(-E, ty, right, 1 + E)]),
        "8": (1, box, [hole(up), hole(lo)]),
        "9": (1, box, [hole(up), open_l(lo)]),
        ":": (0.30, [(0, 0.20, 0.30, 0.40), (0, 0.60, 0.30, 0.80)], []),
        "/": (0.50, [], []),                                 # SLASH, four corners rather than a rectangle
        "°": (0.46, [(0, 0, 0.46, 0.36)], [(0.147, 0.108, 0.313, 0.252)]),
        "-": (0.60, [(0, bar0, 0.60, bar1)], []),            # a minus, and the dash of a missing reading
        # Two hollow boxes either side of PERCENT
        "%": (0.80, [(0, 0, 0.30, 0.36), (0.50, 0.64, 0.80, 1)],
              [(ty * 0.45, ty * 0.45, 0.30 - ty * 0.45, 0.36 - ty * 0.45),
               (0.50 + ty * 0.45, 0.64 + ty * 0.45, 0.80 - ty * 0.45, 1 - ty * 0.45)]),
    }
    return table[ch]


def thousandths(x):
    return int(round(x * 1000))


def flat(ch, weight):
    """[width, fills, then each fill's rectangle, then each cut's]"""
    w, fills, cuts = glyph(ch, weight)
    out = [thousandths(w), len(fills)]
    for r in fills + cuts:
        out += [thousandths(v) for v in r]
    return out


def main():
    lines = ["// Generated by designs/gen_lockup.py; regenerate, don't edit.",
             "import Toybox.Lang;", "",
             "// Lockup's own numerals, in thousandths of a block a thousand units tall:",
             "// [width, how many fills, then each fill's rectangle (u0, v0, u1, v1), then",
             "// each cut's]. In the order 0123456789:/°-% (see index).",
             "module Digits {", ""]
    for name in WEIGHTS:
        rows = ",\n        ".join(str(flat(c, name)) for c in CHARS)
        lines.append(f"    const {name} = [\n        {rows}\n    ] as Array<Array<Number>>;\n")
    lines += [f"    const SLASH = {[thousandths(v) for v in SLASH]} as Array<Number>;",
              f"    const PERCENT = {[thousandths(v) for v in PERCENT]} as Array<Number>;", "",
              "    // The slanting stroke's four corners, for the characters that have one",
              "    function slant(i as Number) as Array<Number>? {",
              f"        if (i == {CHARS.index('/')}) {{ return SLASH; }}",
              f"        if (i == {CHARS.index('%')}) {{ return PERCENT; }}",
              "        return null;", "    }", "",
              "    // A character's place in the tables, or -1 for one the numerals don't have",
              "    function index(c as Char) as Number {",
              "        var n = c.toNumber();",
              "        if (n >= 48 && n <= 57) { return n - 48; }",
              "        if (n == 58) { return 10; }",
              "        if (n == 47) { return 11; }",
              "        if (n == 176) { return 12; }",
              "        if (n == 45) { return 13; }",
              "        if (n == 37) { return 14; }",
              "        return -1;", "    }", "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf8")
    print(OUT)


if __name__ == "__main__":
    main()
