def scale(c, f):
    return tuple(min(255, int(((c >> s) & 0xFF) * f)) for s in (16, 8, 0))


def pack(t):
    return (t[0] << 16) | (t[1] << 8) | t[2]


def dim(c, f):
    """`c` at `f` of its brightness"""
    return pack(scale(c, f))


def wash(c, f):
    """`c` taken `f` of the way to white"""
    return pack(tuple(int(v + (255 - v) * f) for v in scale(c, 1.0)))


