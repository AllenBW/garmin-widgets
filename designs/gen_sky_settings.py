#!/usr/bin/env python3
"""Generate a sky face's colours and settings (Daylight, Horizon, Night
Sky) from one description, so the watch face editor, the phone app's list
and the watch's own settings menu offer the same choices, and the face
draws only colours its sky can have:

- Look (first on the phone): your sky, high visibility in orange, blue or
  green, low light, or a new sky each day (Lib.Look); holding the face on
  the watch steps through the same six
- Theme ("Sky" on the phone): the face's named skies, each a whole palette
  (a dial's night, day and golden hours; a bezel's dry hours, dark hours
  and rain; a night's stars, lines and planets). The daily look steps
  through the same skies, each with its own time colour
- TimeColor: the time's colour (and the hand's), from a short list of
  lights the sky has (daylight, moonlight, starlight...), not any colour
- the fēnix 8's watch face editor (resources/configs/watchface.xml): the
  style is the sky, the accent colour the time's colour, offering only the
  face's list (no "any colour"); the face snaps anything else to the
  nearest. There is no data colour: the sky holds the rest

    python3 -I designs/gen_sky_settings.py daylight|horizon|nightsky

Writes source/Skies.mc (the palettes and the reader: whichever of the
phone and the editor was changed last wins), source/Choices.mc (the watch's
menu, Lib.WatchMenu), resources/configs/watchface.xml,
resources/settings/properties.xml and settings.xml, and
resources/strings/strings.xml whole. Regenerate rather than edit the
output. Every first sky and first time colour is the face as it was
before it had settings, so the defaults draw it unchanged.
"""
