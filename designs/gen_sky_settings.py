    s += '        <settingConfig type="list">\n'
    s += "".join(f'            <listEntry value="{i}">@Strings.Look{k}</listEntry>\n' for k, _, i in LOOKS)
    s += "        </settingConfig>\n    </setting>\n"
    s += lst("Theme", "ThemeTitle", [(i, "Sky" + key(n)) for i, (n, _) in enumerate(skies)])
    s += lst("TimeColor", "TimeTitle", [(i, "Time" + key(n)) for i, (n, _) in enumerate(times)])
    s += "</settings>\n"
    (res / "settings/settings.xml").write_text(s)

