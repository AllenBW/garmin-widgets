#!/usr/bin/env python3
"""Generate a face's settings resources from one description, so the
watch face editor (resources/configs/watchface.xml) and the phone app's
settings list (resources/settings/*.xml) always offer the same choices,
the ones Lib.Config.read expects:

- Style: the face's styles (here, its typefaces)
- Accent: any colour in the editor; the eight below on the phone
- DataColor: Bone, Silver, Sand, Ice, Blush
- Reading1..ReadingN: any complication in the editor; on the phone, the Garmin
  readings Lib.Slots has an icon and a word for
- Bedside: the dim red bedside clock in standby during sleep hours

    python3 designs/gen_face_settings.py vessel|inscription|overlap

The readings' properties were Slot1..SlotN until their defaults changed
(November 2026); new names, so a watch that kept the old values takes
the new defaults. Regenerate rather than edit the output. resources/strings/strings.xml is
written whole too; the face's own strings go in FACES below.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

ACCENTS = [("Amber", "0xFFB020"), ("Lime", "0x8CE03C"), ("Sky", "0x38A8FF"), ("Flame", "0xFF5A36"),
           ("Mint", "0x2EE6B0"), ("Violet", "0xA77BFF"), ("Rose", "0xFF5C9E"), ("Gold", "0xE8D44A")]
DATA = [("Bone", "0xF2ECE2"), ("Silver", "0xB4BAC2"), ("Sand", "0xE6CFA0"), ("Ice", "0xCFE6FF"), ("Blush", "0xF8D2D8")]

# Complications.Type numbers (the SDK's api.mir) and their names, in the
# phone list's order. Sunrise stands for both sun events: Lib.Slots.SUN
# shows whichever comes next.
READINGS = [(18, "Heart rate"), (2, "Steps"), (1, "Watch battery"), (23, "Body Battery"), (22, "Stress"),
            (38, "Temperature"), (8, "Weather"), (3, "Calories"), (4, "Floors climbed"), (5, "Intensity minutes"),
            (15, "Altitude"), (35, "Pulse Ox"), (36, "Respiration"), (13, "Sunrise and sunset"),
            (17, "Notifications"), (21, "Recovery time"), (24, "VO2 max, running"), (25, "VO2 max, cycling"),
            (42, "Sleep score"), (16, "Pressure"), (12, "Next calendar event")]
TYPES = {n: t for t, n in READINGS}

FACES = {
    "vessel": dict(
        name="Vessel",
        what="the digits fill like glasses to two readings (VesselView)",
        styles=["Bionic", "Condensed", "Rajdhani"],
        style_what="the time's typeface (Lib.Ink.BIONIC_BOLD, CONDENSED_BOLD, BIONIC_MEDIUM)",
        accent_what="the minutes and their glass",
        data_what="the hours, their glass and the date",
        slots=[("The hours' glass", "Weather"), ("The minutes' glass", "Heart rate"),
               ("Reading at the foot", "Sunrise and sunset")],
    ),
    "inscription": dict(
        name="Inscription",
        what="the readings set round the rim like a coin's legend (InscriptionView)",
        styles=["Pridi", "Bionic", "Condensed", "Rajdhani"],
        style_what="the typeface (Lib.Ink.PRIDI, BIONIC_BOLD, CONDENSED_BOLD, BIONIC_MEDIUM; Pridi sets the legend too)",
        accent_what="the minutes and the date",
        data_what="the hours and the legend",
        slots=[("Left of the rim", "Weather"), ("Right of the rim", "Pressure"),
               ("Bottom left", "Heart rate"), ("Bottom middle", "Steps"), ("Bottom right", "Sunrise and sunset")],
    ),
    "overlap": dict(
        name="Overlap",
        what="the hours enormous and quiet behind the minutes (OverlapView)",
        styles=["Bionic", "Condensed", "Rajdhani"],
        style_what="the time's typeface (Lib.Ink.BIONIC_BOLD, CONDENSED_BOLD, BIONIC_MEDIUM)",
        accent_what="the minutes and the date",
        data_what="the hours (drawn dim) and the readings",
        slots=[("First reading", "Sunrise and sunset"), ("Second reading", "Weather")],
    ),
}

HEAD = '<{0} xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="https://developer.garmin.com/downloads/connect-iq/resources.xsd">\n'
NOTE = "    <!-- Generated by designs/gen_face_settings.py; regenerate, don't edit. -->\n"


def key(s):
    return "".join(w.capitalize() for w in s.replace(",", "").replace("'", "").split())


def main(face):
    f = FACES[face]
    res = ROOT / "apps" / face / "resources"
    slots = f["slots"]

    cfg = HEAD.format("resources") + NOTE
    cfg += f"""    <!-- The fēnix 8's own watch face editor (Watch Face > {f['name']} > Customize), which
         previews each change live: {f['what']}. The style is {f['style_what']};
         the accent colour (any) lights {f['accent_what']}; the data colour {f['data_what']}.
         The phone app's settings list has the same choices (resources/settings); Lib.Config.read
         takes whichever was changed last. -->
    <watchface-config>
        <styles>
"""
    for i, s in enumerate(f["styles"]):
        cfg += f'            <style id="{i}" label="@Strings.Style{key(s)}"{" default=\"true\"" if i == 0 else ""}/>\n'
    cfg += "        </styles>\n        <accentColors allowAny=\"true\"/>\n        <dataColors>\n"
    for i, (n, c) in enumerate(DATA):
        cfg += f'            <color label="@Strings.Data{n}"{" default=\"true\"" if i == 0 else ""}>{c}</color>\n'
    cfg += "        </dataColors>\n        <data>\n"
    for i, (title, _) in enumerate(slots):
        cfg += f'            <!-- {title.lower()} -->\n            <complication id="{i + 1}" allowAny="true"/>\n'
    cfg += "        </data>\n    </watchface-config>\n</resources>\n"
    (res / "configs").mkdir(parents=True, exist_ok=True)
    (res / "configs/watchface.xml").write_text(cfg)

    p = HEAD.format("properties") + NOTE
    p += f"    <!-- The style: {', '.join(f'{i} {s}' for i, s in enumerate(f['styles']))} -->\n"
    p += '    <property id="Style" type="number">0</property>\n'
    p += f"    <!-- Lib.Config.ACCENTS: {', '.join(f'{i} {n}' for i, (n, _) in enumerate(ACCENTS))} -->\n"
    p += '    <property id="Accent" type="number">0</property>\n'
    p += f"    <!-- Lib.Config.DATA: {', '.join(f'{i} {n}' for i, (n, _) in enumerate(DATA))} -->\n"
    p += '    <property id="DataColor" type="number">0</property>\n'
    p += "    <!-- The readings as Complications.Type numbers -->\n"
    for i, (title, default) in enumerate(slots):
        p += f'    <!-- {title} -->\n    <property id="Reading{i + 1}" type="number">{TYPES[default]}</property>\n'
    p += "    <!-- Standby turns into a dim red bedside clock during the watch's sleep hours -->\n"
    p += '    <property id="Bedside" type="boolean">true</property>\n</properties>\n'
    (res / "settings").mkdir(parents=True, exist_ok=True)
    (res / "settings/properties.xml").write_text(p)

    def lst(prop, title, entries):
        s = f'    <setting propertyKey="@Properties.{prop}" title="@Strings.{title}">\n        <settingConfig type="list">\n'
        s += "".join(f'            <listEntry value="{v}">@Strings.{sid}</listEntry>\n' for v, sid in entries)
        return s + "        </settingConfig>\n    </setting>\n"

    s = HEAD.format("settings") + NOTE
    s += lst("Style", "StyleTitle", [(i, "Style" + key(n)) for i, n in enumerate(f["styles"])])
    s += lst("Accent", "AccentTitle", [(i, "Accent" + n) for i, (n, _) in enumerate(ACCENTS)])
    s += lst("DataColor", "DataTitle", [(i, "Data" + n) for i, (n, _) in enumerate(DATA)])
    for i, (title, _) in enumerate(slots):
        s += lst(f"Reading{i + 1}", f"Slot{i + 1}Title", [(t, "Reading" + key(n)) for t, n in READINGS])
    s += '    <setting propertyKey="@Properties.Bedside" title="@Strings.BedsideTitle">\n'
    s += '        <settingConfig type="boolean"/>\n    </setting>\n</settings>\n'
    (res / "settings/settings.xml").write_text(s)

    st = HEAD.format("strings") + NOTE
    st += f'    <string id="AppName">{f["name"]}</string>\n'
    st += '    <string id="StyleTitle">Typeface</string>\n'
    st += "".join(f'    <string id="Style{key(n)}">{n}</string>\n' for n in f["styles"])
    st += '    <string id="AccentTitle">Accent color</string>\n'
    st += "".join(f'    <string id="Accent{n}">{n}</string>\n' for n, _ in ACCENTS)
    st += '    <string id="DataTitle">Data color</string>\n'
    st += "".join(f'    <string id="Data{n}">{n}</string>\n' for n, _ in DATA)
    st += "".join(f'    <string id="Slot{i + 1}Title">{t}</string>\n' for i, (t, _) in enumerate(slots))
    st += "".join(f'    <string id="Reading{key(n)}">{n}</string>\n' for _, n in READINGS)
    st += '    <string id="BedsideTitle">Bedside clock in standby during sleep hours</string>\n</strings>\n'
    (res / "strings").mkdir(parents=True, exist_ok=True)
    (res / "strings/strings.xml").write_text(st)
    print(f"{face}: {len(f['styles'])} styles, {len(slots)} slots")


if __name__ == "__main__":
    main(sys.argv[1])
