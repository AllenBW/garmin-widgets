#!/usr/bin/env python3
"""Generate apps/wall/source/Numerals.mc: which cells of Wall's wall of
digits each big numeral lights.

The wall is a grid over the screen (cells 0.025 wide, 0.0375 tall). The time
is two Bionic Bold numbers 0.405 tall, the hours above the band of readings
and the minutes below it, each of two tabular digits centred on the screen.
A cell is lit when at least five of nine points in it fall inside the numeral;
its edge when it is lit and a neighbour's centre falls outside. Standby keeps
only the edges. Both digits' columns land on the same half cell, so a digit
needs one table per block (hours, minutes), not one per place.

    python3 -I designs/gen_wall.py      (needs Pillow)

Regenerate rather than edit the output. A watch face can't afford this at
run time: the watchdog allows a few thousand calls an update.
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONTS = Path.home() / "Library/Application Support/Garmin/ConnectIQ/Fonts"
OUT = Path(__file__).resolve().parent.parent / "apps/wall/source/Numerals.mc"
SS = 1816                     # the sampling grid, per screen width

CW, CH = 0.0250, 0.0375       # WallView.CELL_W, CELL_H
TALL = 0.405                  # WallView.TALL
TOPS = (0.046, 0.549)         # WallView.TOPS: the numerals' tops
BAND = (0.462, 0.538)         # WallView.BAND: no cells here
COLS = int(1 / CW) + 1
ROWS = int(1 / CH) + 1
OX = (1 - COLS * CW) / 2
OY = (1 - ROWS * CH) / 2


def masks():
    probe = ImageFont.truetype(str(FONTS / "Bionic_Bold.ttf"), 1000)
    _, dy0, _, dy1 = probe.getbbox("0")
    em = TALL * SS * 1000 / (dy1 - dy0)
    f = ImageFont.truetype(str(FONTS / "Bionic_Bold.ttf"), int(em))
    adv = f.getlength("0") / SS
    tops = f.getbbox("0")[1]
    column = (0.5 - adv - OX) / CW                 # the first digit's pen, in cells
    second = (0.5 - OX) / CW
    assert abs((column % 1) - (second % 1)) < 0.05, (column, second)
    phase = column % 1
    tables = []
    for top in TOPS:
        per_digit = []
        for d in range(10):
            im = Image.new("L", (int(adv * SS) + 8, SS), 0)
            ImageDraw.Draw(im).text((0, top * SS - tops), str(d), font=f, fill=255)
            px = im.load()
            width, height = im.size

            def inside(x, y):
                ix, iy = int(x * SS), int(y * SS)
                return 0 <= ix < width and 0 <= iy < height and px[ix, iy] > 128

            n_cols = int(adv / CW) + 2

            def cell_x(j):
                return (j - phase) * CW     # a cell's left, from the pen

            def on(r, j):
                x, y = cell_x(j), OY + r * CH
                if y + CH > BAND[0] and y < BAND[1]:
                    return False
                cx, cy = x + CW / 2, y + CH / 2
                n = sum(inside(cx + dx * CW, cy + dy * CH) for dx in (-.25, 0, .25) for dy in (-.25, 0, .25))
                return n >= 5

            rows = {}
            for r in range(ROWS):
                lit = edge = 0
                for j in range(n_cols):
                    if on(r, j):
                        lit |= 1 << j
                        x, y = cell_x(j) + CW / 2, OY + r * CH + CH / 2
                        neighbours = ((x + CW, y), (x - CW, y), (x, y + CH), (x, y - CH))
                        if not all(inside(a, b) for a, b in neighbours):
                            edge |= 1 << j
                if lit:
                    rows[r] = (lit, edge)
            per_digit.append(rows)
        tables.append(per_digit)
    return tables, int(column), int(second)


def main():
    tables, first, second = masks()
    start = [min(min(rows) for rows in per_digit) for per_digit in tables]
    end = [max(max(rows) for rows in per_digit) for per_digit in tables]
    lines = ["import Toybox.Lang;", "",
             "// Generated by designs/gen_wall.py; regenerate, don't edit.",
             "// Which cells of the wall each big numeral lights: one bit per column from",
             "// the digit's first column, a row of numbers per grid row from START.",
             "module Numerals {", "",
             f"    const FIRST = {first};       // the column where the first digit's table starts",
             f"    const SECOND = {second};      // and the second's",
             f"    const START = {start} as Array<Number>;      // the first grid row, hours then minutes",
             f"    const COUNT = {[e - s + 1 for s, e in zip(start, end)]} as Array<Number>;       // how many rows", ""]
    for name, index, doc in (("LIT", 0, "lit"), ("EDGE", 1, "on the numeral's edge")):
        lines.append(f"    // Cells {doc}: [block][digit][row]")
        lines.append(f"    const {name} = [")
        for b, per_digit in enumerate(tables):
            lines.append("        [")
            for rows in per_digit:
                nums = [rows.get(r, (0, 0))[index] for r in range(start[b], end[b] + 1)]
                lines.append("            [" + ", ".join(map(str, nums)) + "] as Array<Number>,")
            lines.append("        ] as Array<Array<Number>>,")
        lines.append("    ] as Array<Array<Array<Number>>>;")
        lines.append("")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{OUT.name}: columns {first}, {second}; rows {start}, {end}")


if __name__ == "__main__":
    main()
