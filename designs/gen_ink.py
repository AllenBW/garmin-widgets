#!/usr/bin/env python3
"""Generate lib/source/Ink.mc: where the digits' ink sits in each of the
watch's vector fonts, so a face can place the time by its ink rather than
by advance widths (pitfalls: a "1" in Roboto Condensed carries 0.155 em of
space on its right).

For each font: the vector font's height per em (getVectorFont's :size is
the font's whole height, ascent plus descent), the digits' ink top and
bottom above the baseline, and each digit's left and right side bearing,
all in thousandths of an em, measured from the TTFs the simulator uses.

    python3 -I designs/gen_ink.py      (needs Pillow)

Regenerate rather than edit the output.
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONTS = Path.home() / "Library/Application Support/Garmin/ConnectIQ/Fonts"
OUT = Path(__file__).resolve().parent.parent / "lib/source/Ink.mc"
EM = 1000

# (enum name, the watch's face name, TTF)
# A face some watches lack, and the one with the same digit height to use there
SUBSTITUTE = {"BIONIC_MEDIUM": "BIONIC_BOLD", "ROBOTO_MEDIUM": "CONDENSED_BOLD"}
FACES = [
    ("BIONIC_BOLD", "BionicBold", "Bionic_Bold.ttf"),
    ("BIONIC_MEDIUM", "BionicMedium", "Bionic_Medium.ttf"),
    ("CONDENSED_BOLD", "RobotoCondensedBold", "RobotoCondensed-Bold.ttf"),
    ("CONDENSED_REGULAR", "RobotoCondensedRegular", "RobotoCondensed-Regular.ttf"),
    ("ROBOTO_MEDIUM", "RobotoMedium", "Roboto-Medium.ttf"),
    ("PRIDI", "PridiRegular", "Pridi-Regular.ttf"),
    # What other watches have in their place: the Venu 3 only Roboto
    # Regular, Yantramanav and Pridi; the epix 2 family Garmin's own Pridi
    ("ROBOTO_REGULAR", "RobotoRegular", "Roboto-Regular.ttf"),
    ("YANTRAMANAV", "YantramanavRegular", "Yantramanav-Regular.ttf"),
    ("PRIDI_GARMIN", "PridiRegularGarmin", "Pridi-Regular_Garmin.ttf"),
]
# For each face, the faces to try in its place on a watch that lacks it,
# nearest width first. Measured at one em against Roboto Condensed Bold:
# Yantramanav is within 3 %, Roboto Regular and Medium 10 % wider, Bionic
# within 5 %; Pridi's Garmin cut has the same widths and a shorter box.
CHAIN = {
    "BIONIC_BOLD": ["CONDENSED_BOLD", "YANTRAMANAV", "ROBOTO_REGULAR"],
    "BIONIC_MEDIUM": ["BIONIC_BOLD", "CONDENSED_BOLD", "YANTRAMANAV", "ROBOTO_REGULAR"],
    "CONDENSED_BOLD": ["YANTRAMANAV", "ROBOTO_REGULAR"],
    "CONDENSED_REGULAR": ["YANTRAMANAV", "ROBOTO_REGULAR"],
    "ROBOTO_MEDIUM": ["ROBOTO_REGULAR", "CONDENSED_BOLD", "YANTRAMANAV"],
    "PRIDI": ["PRIDI_GARMIN", "YANTRAMANAV", "ROBOTO_REGULAR"],
    "ROBOTO_REGULAR": ["YANTRAMANAV", "CONDENSED_REGULAR"],
    "YANTRAMANAV": ["CONDENSED_REGULAR", "ROBOTO_REGULAR"],
    "PRIDI_GARMIN": ["PRIDI", "YANTRAMANAV", "ROBOTO_REGULAR"],
}


def ink(f, s):
    """The ink box of s drawn with its pen at (0, 0) on the baseline,
    found from the rendered pixels."""
    pad = EM
    img = Image.new("L", (3 * EM * len(s), 3 * EM), 0)
    ImageDraw.Draw(img).text((pad, 2 * EM), s, font=f, fill=255, anchor="ls")
    x0, y0, x1, y1 = img.point(lambda v: 255 if v > 127 else 0).getbbox()
    return x0 - pad, y0 - 2 * EM, x1 - pad, y1 - 2 * EM


def measure(ttf):
    f = ImageFont.truetype(str(FONTS / ttf), EM)
    ascent, descent = f.getmetrics()
    bear = []
    for d in "0123456789":
        x0, _, x1, _ = ink(f, d)
        bear += [x0, round(f.getlength(d) - x1)]
    _, top, _, bottom = ink(f, "0123456789")
    return ascent + descent, -top, -bottom, bear


def main():
    rows = [(name, face, *measure(ttf)) for name, face, ttf in FACES]
    names = [r[0] for r in rows]
    arr = lambda xs: "[" + ", ".join(str(x) for x in xs) + "] as Array<Number>"  # noqa: E731
    out = f'''import Toybox.Graphics;
import Toybox.Lang;

// Generated by designs/gen_ink.py from the watch's TTFs; regenerate, don't edit.
module Lib {{

    // Where the digits' ink sits in each of the watch's vector fonts, so a
    // face places the time by its ink, not by advance widths. All in
    // thousandths of an em.
    (:ink)
    module Ink {{

        enum Face {{ {", ".join(r[0] for r in rows)} }}

        const NAMES = [{", ".join('"' + r[1] + '"' for r in rows)}] as Array<String>;
        // getVectorFont's :size for a one-em font: its ascent plus descent
        const HEIGHT = {arr(r[2] for r in rows)};
        // The digits' ink top and bottom above the baseline
        const TOP = {arr(r[3] for r in rows)};
        const BOTTOM = {arr(r[4] for r in rows)};
        // Each digit's left then right side bearing, 0 to 9, per face
        const BEAR = [
{chr(10).join("            " + arr(r[5]) + "," for r in rows)}
        ] as Array<Array<Number>>;
        // For each face, the faces to try in its place on a watch that
        // lacks it, nearest width first (the fenix 8 family has them all;
        // the Venu 3 only Roboto Regular, Yantramanav and Pridi)
        const CHAIN = [
{chr(10).join("            " + arr(names.index(c) for c in CHAIN[r[0]]) + "," for r in rows)}
        ] as Array<Array<Number>>;

        var _have as Array<Boolean?>? = null;

        // Whether this watch has the face, asked of the watch once
        function present(face as Number) as Boolean {{
            if (_have == null) {{
                _have = new [NAMES.size()] as Array<Boolean?>;
            }}
            var h = (_have as Array<Boolean?>)[face];
            if (h == null) {{
                h = (Graphics has :getVectorFont) && Graphics.getVectorFont({{:face => NAMES[face], :size => 20}}) != null;
                (_have as Array<Boolean?>)[face] = h;
            }}
            return h;
        }}

        // The face where the watch has it, else the nearest in its chain
        // the watch has; the face itself when it has none of them. Pick
        // the face with this once, and measure with the same index, so
        // the metrics match the font drawn.
        function resolve(face as Number) as Number {{
            if (present(face)) {{
                return face;
            }}
            var chain = CHAIN[face];
            for (var i = 0; i < chain.size(); i++) {{
                if (present(chain[i])) {{
                    return chain[i];
                }}
            }}
            return face;
        }}

        // The em, in px, that makes the digits `digits` px tall
        function em(face as Number, digits as Float) as Float {{
            return digits * 1000.0 / (TOP[face] - BOTTOM[face]);
        }}

        // Faces some watches lack (the Venu 4 has no Bionic Medium or Roboto
        // Medium) and the sibling with the same digit height to use instead
        const SUBSTITUTE = [{", ".join(SUBSTITUTE.get(r[0], "-1") for r in rows)}] as Array<Number>;
        var usableFaces as Array<Number?> = [{", ".join("null" for r in rows)}] as Array<Number?>;

        // `face` where this watch has it, else its sibling: draw and measure
        // with the same one, so a layout's widths match its digits
        function usable(face as Number) as Number {{
            var u = usableFaces[face];
            if (u == null) {{
                u = face;
                if (SUBSTITUTE[face] >= 0 && (Graphics has :getVectorFont)) {{
                    var f = null;
                    try {{
                        f = Graphics.getVectorFont({{:face => NAMES[face], :size => 40}});
                    }} catch (e) {{
                        f = null;
                    }}
                    if (f == null) {{
                        u = SUBSTITUTE[face];
                    }}
                }}
                usableFaces[face] = u;
            }}
            return u;
        }}

        // The vector font for that em, or the fallback where there is none
        function font(face as Number, em as Float, fallback as FontType) as FontType {{
            if (Graphics has :getVectorFont) {{
                var f = Graphics.getVectorFont({{:face => NAMES[face], :size => (em * HEIGHT[face] / 1000.0).toNumber()}});
                if (f != null) {{
                    return f;
                }}
            }}
            return fallback;
        }}

        // From the pen to the ink's left edge of `s`
        function left(face as Number, s as String, em as Float) as Float {{
            var d = digit(s, 0);
            return (d != null) ? BEAR[face][d * 2] * em / 1000.0 : 0.0;
        }}

        // From the ink's right edge of `s` to the end of its advance
        function right(face as Number, s as String, em as Float) as Float {{
            var d = digit(s, s.length() - 1);
            return (d != null) ? BEAR[face][d * 2 + 1] * em / 1000.0 : 0.0;
        }}

        // The y to pass drawText (justified top) so the digits' ink is
        // centred on `mid`
        function top(face as Number, font as FontType, mid as Float, em as Float) as Float {{
            return mid + (TOP[face] + BOTTOM[face]) * em / 2000.0 - Graphics.getFontAscent(font);
        }}

        // The digits' ink height for this em
        function height(face as Number, em as Float) as Float {{
            return (TOP[face] - BOTTOM[face]) * em / 1000.0;
        }}

        function digit(s as String, i as Number) as Number? {{
            if (i < 0 || i >= s.length()) {{
                return null;
            }}
            var c = s.substring(i, i + 1);
            return (c != null) ? c.toNumber() : null;
        }}
    }}
}}
'''
    OUT.write_text(out)
    for r in rows:
        print(r[0], "height", r[2], "top", r[3], "bottom", r[4])


if __name__ == "__main__":
    main()
