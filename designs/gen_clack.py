#!/usr/bin/env python3
"""Generate the Clack face's tables and bitmap fonts from the approved
preview (designs/preview_clack.py), so the watch draws the same geometry
the owner saw on the states page:

- apps/clack/source/Layout.mc: per device width (454, 416) and style, the
  leaves' geometry in pixels (digit height, leaf width and height, the
  hinge, each leaf's x, the slot, corners, pins, stack step, the captions'
  lines), and the lamp's brightness at each leaf
- apps/clack/source/Drops.mc: the roll's drop tables, the leaf's angle at
  each frame after it slips off the stop (preview_clack.roll_profile with
  no push; the push is computed on the watch)
- apps/clack/resources-round-<w>x<w>/fonts/: a BMFont (.fnt + .png mask)
  per style that needs one: the condensed faces' digits (the watch has no
  condensed vector font) and every zoomed style's standby glyphs (the
  outline, or Roboto's eroded fill, pre-rendered), with fonts.xml

    uv run --with pillow python -I designs/gen_clack.py

The styles: 0 the original view (Roboto Condensed Bold, the watch's own
vector font), 1 to 4 the zoomed-in view in League Gothic, Antonio Bold,
Bebas Neue and Roboto. Regenerate rather than edit the output.
"""
import math
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageOps

sys.path.insert(0, str(Path(__file__).resolve().parent))   # run with -I
import preview_clack as pc  # noqa: E402
from preview_faces import SS, ink_box, glyph_mask, outline_of  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "apps" / "clack"
STYLES = [("original", "0", "roboto"), ("league", "1", "league"), ("antonio", "1", "antonio"),
          ("bebas", "1", "bebas"), ("robotozoom", "1", "roboto")]
FONT_INDEX = {"roboto": 0, "league": 1, "antonio": 2, "bebas": 3}
WIDTHS = [454, 416]
FPS = 20
DROPS = 12          # drop tables; each flip picks one and draws its own push
PAD = 2             # px round each glyph in the bitmap fonts, room for the outlines


def clack(w, style):
    _, zoom, font = STYLES[style]
    return pc.Clack(w, {**pc.DEFAULTS, "zoom": zoom, "font": font})


def geometry(w, style):
    """One style's layout on one device, in whole pixels (the hinge keeps
    its half pixel as the preview has it)."""
    c = clack(w, style)
    S = c.S
    px = lambda v: int(round(v / SS))
    h = c.ch // 2
    return dict(
        digit=px(S(c.H)), leafW=px(c.cards[0][1]), leafH=px(c.ch), y0=px(c.y0), hinge=px(c.y0 + h),
        x=[px(ox) for ox, _ in c.cards], cx=[px(S(v)) for v in c.centres],
        slot=px(S(c.L["slot"]) / 2), corner=px(S(c.L["corner"])), pin=px(S(c.L["pin"])), step=px(S(c.L["stack_step"])),
        captionY=px(S(c.L["caption_y"])) if c.L["caption"] == "leaf" else 0,
        dateY=px(S(c.date_y)) if c.L["caption"] == "below" else 0,
        small=px(S(c.L["date_em"])), zoomed=1 if c.L["caption"] == "leaf" else 0, font=FONT_INDEX[STYLES[style][2]],
        aod=1 if pc.FONT[STYLES[style][2]][4] == "fill" else 0,
    )


def lamp_factors(w):
    """The lamp's brightness over each leaf (0 to 1): the mean of the
    preview's lamp mask across the leaf, in the original and zoomed layouts
    (the leaves sit in the same columns in both)."""
    out = []
    for style in (0, 1):
        c = clack(w, style)
        m = pc.lamp_mask(c.face, c.face.img.size, 0, 0)
        row = []
        for ox, cw in c.cards:
            box = (int(ox), int(c.y0), int(ox + cw), int(c.y0 + c.ch))
            box = (max(0, box[0]), max(0, box[1]), min(m.size[0], box[2]), min(m.size[1], box[3]))
            crop = m.crop(box)
            hist = crop.histogram()
            total = sum(hist)
            row.append(round(sum(i * n for i, n in enumerate(hist)) / total / 255.0, 3) if total else 0.0)
        out.append(row)
    return out


def mc_list(values, kind="Number"):
    return "[" + ", ".join(str(v) for v in values) + "] as Array<" + kind + ">"


def write_layout():
    lines = ["import Toybox.Lang;", "", "// Generated by designs/gen_clack.py from designs/preview_clack.py; regenerate, don't edit.",
             "module Layout {", "",
             "    // The styles: 0 the original view in Roboto Condensed Bold, 1 to 4 the zoomed-in view in",
             "    // League Gothic, Antonio Bold, Bebas Neue and Roboto",
             "    const STYLES = %d;" % len(STYLES),
             "    enum Font { ROBOTO, LEAGUE, ANTONIO, BEBAS }",
             "    // A style's table: [digit height, leaf width, leaf height, leaf top y, hinge y, x of leaves 0 to 3,",
             "    // x of their digits' centres, the slot's half width, the corner radius, the pin radius, the stack's",
             "    // step, the captions' centre line on the lower flaps (zoomed) or under the leaves (original), the",
             "    // captions' em, zoomed, the font, standby as an eroded fill (1) or outlines (0)]",
             "    enum Field { DIGIT, LEAF_W, LEAF_H, Y0, HINGE, X0, X1, X2, X3, CX0, CX1, CX2, CX3, SLOT, CORNER, PIN, STEP,",
             "                 CAPTION_Y, SMALL, ZOOMED, FONT, AOD_FILL }"]
    for w in WIDTHS:
        rows = []
        for style in range(len(STYLES)):
            g = geometry(w, style)
            caption = g["captionY"] if g["zoomed"] else g["dateY"]
            rows.append([g["digit"], g["leafW"], g["leafH"], g["y0"], g["hinge"]] + g["x"] + g["cx"] +
                        [g["slot"], g["corner"], g["pin"], g["step"], caption, g["small"], g["zoomed"], g["font"], g["aod"]])
        lines.append("    const W%d = [" % w)
        for row in rows:
            lines.append("        %s," % mc_list(row))
        lines.append("    ] as Array<Array<Number>>;")
        lamps = lamp_factors(w)
        lines.append("    // The lamp's brightness over leaves 0 to 3 after sunset, original then zoomed (preview_clack.lamp_mask)")
        lines.append("    const LAMP%d = [%s, %s] as Array<Array<Float>>;" % (w, mc_list(lamps[0], "Float"), mc_list(lamps[1], "Float")))
    lines += ["", "    function table(w as Number, style as Number) as Array<Number> {",
              "        return ((w >= 440) ? W454 : W416)[style];", "    }", "",
              "    function lamp(w as Number, zoomed as Boolean) as Array<Float> {",
              "        return ((w >= 440) ? LAMP454 : LAMP416)[zoomed ? 1 : 0];", "    }", "}", ""]
    (APP / "source" / "Layout.mc").write_text("\n".join(lines))


def write_drops():
    lines = ["import Toybox.Lang;", "", "// Generated by designs/gen_clack.py (preview_clack.roll_profile at %d fps); regenerate, don't edit." % FPS,
             "module Drops {", "",
             "    // A leaf's angle at each frame from the moment it slips off the stop: the release angle first,",
             "    // then the fall under gravity against the air and the leaf beneath, the bounce and the rest at",
             "    // 180. Each flip picks a table and draws its own push (Roll.profile).",
             "    const TABLES = ["]
    for seed in range(1, DROPS + 1):
        frames = pc.roll_profile(FPS, seed, None, 0)
        angles = [round(th, 1) for th, _ in frames]
        lines.append("        %s," % mc_list(["%.1f" % a for a in angles], "Float"))
    lines += ["    ] as Array<Array<Float>>;", "", "    const COUNT = %d;" % DROPS, "}", ""]
    (APP / "source" / "Drops.mc").write_text("\n".join(lines))


def glyphs(c, standby):
    """Each digit's mask at the face's supersampled scale, cropped to a
    cell: the digits' common vertical ink box, its own ink width, PAD px
    round it. standby: the outline, or the eroded fill above the hinge
    with the outline below (Roboto), as preview_clack.sleeping draws them;
    'A' to 'J' are the hour digits' standby forms where they differ."""
    S = c.S
    d = ink_box(c.font, "0123456789")
    top, bottom = d[1], d[3]
    H = c.ch // 2                                            # the hinge in card coordinates
    out = []
    forms = [("%d" % n, n, False) for n in range(10)]
    if standby and c.L["aod_erode"] and pc.FONT[c.st["font"]][4] == "fill":
        forms += [(chr(ord("A") + n), n, True) for n in range(10)]
    for ch, n, hours in forms:
        t = str(n)
        b = ink_box(c.font, t)
        x0 = S(0.5)                                         # draw at the face's centre, then crop
        basey = S(0.5) - (top + bottom) / 2
        m = glyph_mask(c.face, c.font, t, x0 - (b[0] + b[2]) / 2, basey)
        if standby:
            erode = c.aod_erode() if pc.FONT[c.st["font"]][4] == "fill" else 0
            if erode:
                m = m.filter(ImageFilter.MinFilter(2 * int(round(erode * SS)) + 1))
            edge = outline_of(m, 2)
            if hours:
                mid = int(S(0.5))
                above = Image.new("L", m.size, 0)
                ImageDraw.Draw(above).rectangle((0, 0, m.size[0], mid - SS), fill=255)
                m = Image.composite(m, Image.composite(edge, Image.new("L", m.size, 0), ImageOps.invert(above)), above)
            else:
                m = edge
        cx = S(0.5)
        half = (b[2] - b[0]) / 2
        cell = (int(cx - half) - PAD * SS, int(basey + top) - PAD * SS, int(cx + half) + PAD * SS, int(basey + bottom) + PAD * SS)
        g = m.crop(cell)
        g = g.resize((max(1, round(g.width / SS)), max(1, round(g.height / SS))), Image.LANCZOS)
        out.append((ch, g))
    return out


def write_font(w, name, c, standby):
    """One BMFont: the glyphs side by side in a grey mask PNG, each cell
    the digit's ink box plus PAD, so TEXT_JUSTIFY_CENTER | VCENTER centres
    the ink as the preview does."""
    gs = glyphs(c, standby)
    gap = 2
    width = sum(g.width for _, g in gs) + gap * (len(gs) + 1)
    height = max(g.height for _, g in gs) + 2 * gap
    sheet = Image.new("L", (width, height), 0)
    x = gap
    chars = []
    for ch, g in gs:
        sheet.paste(g, (x, gap))
        chars.append((ord(ch), x, gap, g.width, g.height))
        x += g.width + gap
    folder = APP / ("resources-round-%dx%d" % (w, w)) / "fonts"
    folder.mkdir(parents=True, exist_ok=True)
    sheet.save(folder / (name + ".png"), optimize=True)
    fnt = ["info face=\"%s\" size=%d bold=0 italic=0 charset=\"\" unicode=1 stretchH=100 smooth=1 aa=1 padding=0,0,0,0 spacing=%d,%d outline=0"
           % (name, height, gap, gap),
           "common lineHeight=%d base=%d scaleW=%d scaleH=%d pages=1 packed=0 alphaChnl=1 redChnl=4 greenChnl=4 blueChnl=4" % (height, height, width, height),
           "page id=0 file=\"%s.png\"" % name, "chars count=%d" % len(chars)]
    for cid, cx, cy, cw, chh in chars:
        fnt.append("char id=%d x=%d y=%d width=%d height=%d xoffset=0 yoffset=0 xadvance=%d page=0 chnl=15" % (cid, cx, cy, cw, chh, cw))
    (folder / (name + ".fnt")).write_text("\n".join(fnt) + "\n")
    return name, len(chars), sheet.size


def write_fonts():
    for w in WIDTHS:
        made = []
        for style, (key, zoom, font) in enumerate(STYLES):
            c = clack(w, style)
            if font != "roboto":
                made.append(write_font(w, key + "_digits", c, False))
            if zoom == "1":
                made.append(write_font(w, key + "_standby", c, True))
        folder = APP / ("resources-round-%dx%d" % (w, w)) / "fonts"
        xml = ["<fonts xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\" xsi:noNamespaceSchemaLocation=\"https://developer.garmin.com/downloads/connect-iq/resources.xsd\">",
               "    <!-- Generated by designs/gen_clack.py; regenerate, don't edit. The digits of the condensed faces",
               "         (League Gothic, Antonio Bold, Bebas Neue: SIL OFL, designs/fonts) and every zoomed style's standby",
               "         glyphs, pre-rendered as grey masks at this device's digit size: drawText colours them. -->"]
        for name, count, size in made:
            fid = "".join(p.capitalize() for p in name.split("_"))
            xml.append("    <font id=\"%s\" filename=\"%s.fnt\" filter=\"%s\"/>" % (fid, name, "0123456789ABCDEFGHIJ" if count > 10 else "0123456789"))
            print("%d %-22s %d glyphs %dx%d" % (w, name, count, size[0], size[1]))
        xml.append("</fonts>")
        (folder / "fonts.xml").write_text("\n".join(xml) + "\n")


if __name__ == "__main__":
    (APP / "source").mkdir(parents=True, exist_ok=True)
    write_layout()
    print("Layout.mc")
    write_drops()
    print("Drops.mc")
    write_fonts()
