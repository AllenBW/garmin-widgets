"""Tally's settings resources: twelve button slots (name, colour, the hours
it shows) and the sheet link, as plain settings in groups. Not one list
("array") setting: Garmin Connect on Android fails to save those
(CIQQA-4751). Writes apps/tally/resources/{strings,settings}/; regenerate
rather than edit. python3 designs/gen_tally_settings.py"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "apps" / "tally" / "resources"
SLOTS = 12
COLOURS = ["Coral", "Amber", "Lime", "Mint", "Sky", "Violet", "Pink", "Bone",
           "Orange", "Teal", "Blue", "Yellow"]  # TallyButtons.COLOURS
# Generic, and nothing the watch already tracks (no fitness, no sleep)
DEFAULTS = {1: ("Meal", 1, -1, 24), 2: ("Drink", 4, -1, 24), 3: ("Medicine", 5, -1, 24), 4: ("Symptom", 0, -1, 24)}
HEADER = ('<{0} xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
          'xsi:noNamespaceSchemaLocation="https://developer.garmin.com/downloads/connect-iq/resources.xsd">\n')


def hour(h):
    return "12 AM" if h == 0 else f"{h} AM" if h < 12 else "12 PM" if h == 12 else f"{h - 12} PM"


def entries(pairs, indent=16):
    return "\n".join(f'{" " * indent}<listEntry value="{v}">@Strings.{s}</listEntry>' for v, s in pairs)


def main():
    strings = {
        "AppName": "Tally", "ButtonName": "Name", "ButtonColour": "Colour",
        "ButtonFrom": "Shown from", "ButtonUntil": "Shown until", "Always": "Always",
        "ButtonSize": "Size", "SizeNormal": "Normal", "SizeLarge": "Large (two places in the ring)",
        "ButtonPrompt": "A name (leave it empty for no button), a colour, a size, and the hours it "
                        "shows on the main screen. The ring holds eight places; a large button "
                        "takes two. Every button is always in the All list.",
        "GlanceTitle": "Glance shows", "GlanceNewest": "The newest entry",
        "SheetTitle": "Google Sheet link",
        "SheetPrompt": "The web app link from the Tally script in your sheet (Deploy, Web app). "
                       "Leave empty to keep entries on the watch only.",
    }
    strings.update({f"Button{i}": f"Button {i}" for i in range(1, SLOTS + 1)})
    strings.update({f"Colour{i}": c for i, c in enumerate(COLOURS)})
    strings.update({f"H{h}": hour(h) for h in range(24)})
    strings["H24"] = "12 AM (midnight)"
    (ROOT / "strings" / "strings.xml").write_text(
        "<strings>\n" + "".join(f'    <string id="{k}">{v}</string>\n' for k, v in strings.items()) + "</strings>\n")

    props, groups = [], []
    for i in range(1, SLOTS + 1):
        name, colour, start, end = DEFAULTS.get(i, ("", (i - 1) % len(COLOURS), -1, 24))
        if i > len(DEFAULTS):
            colour = (i - 1) % len(COLOURS)
        props.append(f'    <property id="B{i}Name" type="string">{name}</property>\n'
                     f'    <property id="B{i}Colour" type="number">{colour}</property>\n'
                     f'    <property id="B{i}From" type="number">{start}</property>\n'
                     f'    <property id="B{i}Until" type="number">{end}</property>\n'
                     f'    <property id="B{i}Size" type="number">1</property>')
        groups.append(f'''    <group id="b{i}" title="@Strings.Button{i}" description="@Strings.ButtonPrompt">
        <setting propertyKey="@Properties.B{i}Name" title="@Strings.ButtonName">
            <settingConfig type="alphaNumeric" maxLength="20"/>
        </setting>
        <setting propertyKey="@Properties.B{i}Colour" title="@Strings.ButtonColour">
            <settingConfig type="list">
{entries((k, f"Colour{k}") for k in range(len(COLOURS)))}
            </settingConfig>
        </setting>
        <setting propertyKey="@Properties.B{i}Size" title="@Strings.ButtonSize">
            <settingConfig type="list">
{entries([(1, "SizeNormal"), (2, "SizeLarge")])}
            </settingConfig>
        </setting>
        <setting propertyKey="@Properties.B{i}From" title="@Strings.ButtonFrom">
            <settingConfig type="list">
{entries([(-1, "Always")] + [(h, f"H{h}") for h in range(24)])}
            </settingConfig>
        </setting>
        <setting propertyKey="@Properties.B{i}Until" title="@Strings.ButtonUntil">
            <settingConfig type="list">
{entries((h, f"H{h}") for h in range(1, 25))}
            </settingConfig>
        </setting>
    </group>''')
    (ROOT / "settings" / "properties.xml").write_text(
        HEADER.format("properties")
        + "    <!-- Generated by designs/gen_tally_settings.py. Edited on the phone (Garmin Connect,\n"
          "         the app's settings) or in the simulator. From -1 is always. -->\n"
        + "\n".join(props) + '\n    <property id="GlanceButton" type="number">0</property>'
        + '\n    <property id="SheetUrl" type="string"></property>\n</properties>\n')
    (ROOT / "settings" / "settings.xml").write_text(
        HEADER.format("settings")
        + "    <!-- Generated by designs/gen_tally_settings.py: twelve buttons, what the glance shows, then the sheet -->\n"
        + "\n".join(groups)
        + '\n    <setting propertyKey="@Properties.GlanceButton" title="@Strings.GlanceTitle">\n'
          '        <settingConfig type="list">\n'
        + entries([(0, "GlanceNewest")] + [(i, f"Button{i}") for i in range(1, SLOTS + 1)], 12)
        + '\n        </settingConfig>\n    </setting>'
        + '\n    <setting propertyKey="@Properties.SheetUrl" title="@Strings.SheetTitle" prompt="@Strings.SheetPrompt">\n'
          '        <settingConfig type="alphaNumeric"/>\n    </setting>\n</settings>\n')


if __name__ == "__main__":
    main()
