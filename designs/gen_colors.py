#!/usr/bin/env python3
"""Write the colour dictionary (designs/colors.py) to the library:

- lib/source/Colors.mc: `Lib.Colors`, every named colour, annotated
  (:colors)
- lib/source/Neon.mc: `Lib.Neon`, the tubes, their sets and the looks in
  tubes for the neon faces, annotated (:neon); it uses Lib.Look

    python3 -I designs/gen_colors.py            # write both
    python3 -I designs/gen_colors.py --check    # is every colour the library draws with named?
    python3 -I designs/gen_colors.py --apps     # list the apps' colours that aren't (a report)

Regenerate rather than edit the output. Look.mc, Config.mc and Numbers.mc
still spell their colours out (they are on every watch as they are);
--check holds them to the dictionary until they read from Lib.Colors.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))                                   # run with -I
from colors import (ACCENTS, C, CORE, FLUORESCENTS, MUTED, MUTED_PARTS, NEON_LOOKS, NEON_SETS,  # noqa: E402
                    NEUTRALS, NIGHT, STANDBY, TUBES)

ROOT = HERE.parent
NOTE = "// Generated by designs/gen_colors.py from designs/colors.py; regenerate, don't edit.\n"
HEX = re.compile(r"0x[0-9A-Fa-f]{6}\b")
MASKS = {0x3F3F3F}                 # Lib.Aod's quarter-brightness mask, not a colour


def x(v):
    return f"0x{v:06X}"


def colors_mc():
    s = NOTE + "import Toybox.Lang;\n\nmodule Lib {\n\n"
    s += "    // The colour dictionary: every named colour the project draws with, by\n"
    s += "    // family. A name is a colour's word in the settings and the looks.\n"
    s += "    (:colors)\n    module Colors {\n"
    for title, family in (("Neutrals: text and data", NEUTRALS), ("Accents", ACCENTS),
                          ("Fluorescents: the high visibility looks", FLUORESCENTS), ("Night", NIGHT)):
        s += f"\n        // {title}\n"
        for name, (value, what) in family.items():
            s += f"        const {name} = {x(value)};".ljust(40) + f"// {what}\n"
    s += "\n        // The muted weeks: each set's neutral, sun, weather and body\n"
    for name, values in MUTED.items():
        for part, value in zip(MUTED_PARTS, values):
            s += f"        const {name}_{part} = {x(value)};\n"
    s += "\n        // Neon tubes: only colours a sign shop bends (Lib.Neon has them in order)\n"
    for name, (value, gas, glass, _) in TUBES.items():
        s += f"        const TUBE_{name} = {x(value)};".ljust(46) + f"// {gas}, {glass}\n"
    return s + "    }\n}\n"


def neon_mc():
    order = list(TUBES)
    idx = order.index

    def trio(names):
        return "[" + ", ".join(str(idx(n)) for n in names) + "] as Array<Number>"

    s = NOTE + "import Toybox.Application;\nimport Toybox.Application.WatchFaceConfig;\nimport Toybox.Lang;\n\nmodule Lib {\n\n"
    s += """    // The neon faces' colours: tubes a sign shop bends, and nothing else.
    // A face has three, the hours', the minutes' and the details', chosen in
    // the phone app (Hours, Minutes, Detail: a tube's number) or in the
    // fēnix 8's watch face editor (the accent colour, the data colour and the
    // style, each offering only the tubes), whichever was changed last, as
    // Lib.Config has it for the other faces; or by the look (Lib.Look): high visibility is a white sign with one strong colour, low
    // light the warm end of the chart, and the daily look one of SETS, the
    // next each day. A tube is drawn as a halo in its colour and a core
    // washed toward white; in standby, the thin tube alone. The numbers are
    // stored on watches, so new tubes and sets go at the end.
    (:neon)
    module Neon {

"""
    for i, name in enumerate(order):
        s += f"        const {name} = {i};\n"
    s += "\n        // " + ", ".join(t[3] for t in TUBES.values()) + "\n"
    s += "        const TUBES = [\n"
    names = list(TUBES)
    for i in range(0, len(names), 4):
        s += "            " + ", ".join(x(TUBES[n][0]) for n in names[i:i + 4]) + ("," if i + 4 < len(names) else "") + "\n"
    s += "        ] as Array<Number>;\n\n"
    s += "        // The daily look's sets: [hours, minutes, details]\n"
    s += "        const SETS = [\n"
    s += ",\n".join(f"            {trio(v)}" for v in NEON_SETS.values()) + "\n        ] as Array<Array<Number>>;\n"
    s += "        const NAMES = [" + ", ".join(f'"{n}"' for n in NEON_SETS) + "] as Array<String>;\n\n"
    s += "        const KEYS = [\"Hours\", \"Minutes\", \"Detail\"] as Array<String>;   // the phone's settings\n"
    first = next(iter(NEON_SETS.values()))
    s += f"        const FIRST = {trio(first)};                 // until one is chosen\n\n"
    s += f"""        const SOURCE = "Source";          // in storage: "phone" or "editor", whichever was changed last
        const PHONE = "phone";
        const EDITOR = "editor";

        // The three tubes chosen: in the phone app, or in the watch face
        // editor unless the phone app was changed since
        function chosen() as Array<Number> {{
            var out = [FIRST[0], FIRST[1], FIRST[2]] as Array<Number>;
            for (var i = 0; i < KEYS.size(); i++) {{
                var v = null;
                try {{
                    v = Application.Properties.getValue(KEYS[i]);
                }} catch (e) {{
                    v = null;
                }}
                if (v instanceof Number && v >= 0 && v < TUBES.size()) {{
                    out[i] = v;
                }}
            }}
            if (Application has :WatchFaceConfig && !PHONE.equals(Application.Storage.getValue(SOURCE))) {{
                var config = WatchFaceConfig.getSettings(null);
                if (config != null) {{
                    var picked = config.accentColor;
                    if (picked != null && picked.color != null) {{
                        out[0] = tubeOf(picked.color as Number);
                    }}
                    picked = config.complicationColor;
                    if (picked != null && picked.color != null) {{
                        out[1] = tubeOf(picked.color as Number);
                    }}
                    var style = config.styleId;
                    if (style != null && style >= 0 && style < TUBES.size()) {{
                        out[2] = style;
                    }}
                }}
            }}
            return out;
        }}

        // The tube nearest a colour: the editor offers only the tubes, so
        // this is the tube itself; anything else snaps to the chart
        function tubeOf(color as Number) as Number {{
            var best = 0;
            var least = -1;
            for (var i = 0; i < TUBES.size(); i++) {{
                var dr = ((TUBES[i] >> 16) & 0xFF) - ((color >> 16) & 0xFF);
                var dg = ((TUBES[i] >> 8) & 0xFF) - ((color >> 8) & 0xFF);
                var db = (TUBES[i] & 0xFF) - (color & 0xFF);
                var d = dr * dr + dg * dg + db * db;
                if (least < 0 || d < least) {{
                    least = d;
                    best = i;
                }}
            }}
            return best;
        }}

        // From onSettingsChanged: the phone app's choices win until the
        // editor is next used (and a new Look there is taken up)
        function changedOnPhone() as Void {{
            Application.Storage.setValue(SOURCE, PHONE);
            Look.changedOnPhone();
        }}

        // From onWatchFaceConfigEdited: the editor's choices win
        function changedInEditor() as Void {{
            Application.Storage.setValue(SOURCE, EDITOR);
        }}

        // The look's tubes, as numbers: `yours` in the face's own look, the
        // set of day `day` (Lib.Look.day(SETS.size())) in the daily one
        function tubes(mode as Number, yours as Array<Number>, day as Number) as Array<Number> {{
            if (mode == Look.BRIGHT) {{
                return {trio(NEON_LOOKS["BRIGHT"])};
            }}
            if (mode == Look.BRIGHT_BLUE) {{
                return {trio(NEON_LOOKS["BRIGHT_BLUE"])};
            }}
            if (mode == Look.BRIGHT_GREEN) {{
                return {trio(NEON_LOOKS["BRIGHT_GREEN"])};
            }}
            if (mode == Look.LOW) {{
                return {trio(NEON_LOOKS["LOW"])};
            }}
            if (mode == Look.DAILY) {{
                return SETS[day % SETS.size()];
            }}
            return yours;
        }}

        // The look's colours now: [hours, minutes, details]
        function colors(mode as Number) as Array<Number> {{
            var t = tubes(mode, chosen(), Look.day(SETS.size()));
            return [TUBES[t[0]], TUBES[t[1]], TUBES[t[2]]] as Array<Number>;
        }}

        // The look's name, in capitals: a set's in the daily look. High
        // visibility's first look is a clear red tube here, not orange
        function title(mode as Number) as String {{
            return (mode == Look.BRIGHT) ? "HI-VIS RED" : Look.title(mode, NAMES);
        }}

        // A lit tube's core: its colour washed toward white
        function core(color as Number) as Number {{
            return wash(color, {round(CORE * 100)}, 100);
        }}

        // A tube in standby: a little washed, dimmed, and drawn with no halo
        function standby(color as Number) as Number {{
            return wash(color, {round(STANDBY[0] * 100)}, {round(STANDBY[1] * 100)});
        }}

        // A colour `toWhite` percent of the way to white, at `level` percent
        function wash(color as Number, toWhite as Number, level as Number) as Number {{
            var r = (color >> 16) & 0xFF;
            var g = (color >> 8) & 0xFF;
            var b = color & 0xFF;
            r = (r + (255 - r) * toWhite / 100) * level / 100;
            g = (g + (255 - g) * toWhite / 100) * level / 100;
            b = (b + (255 - b) * toWhite / 100) * level / 100;
            return (r << 16) | (g << 8) | b;
        }}
    }}
}}
"""
    return s


def literals(path):
    """The colour literals in a source file, comments aside."""
    out = set()
    for line in path.read_text().splitlines():
        out |= {int(m, 16) for m in HEX.findall(line.split("//")[0])}
    return out - MASKS


def check():
    named = set(C.values())
    bad = 0
    for f in ("Look.mc", "Config.mc", "Numbers.mc"):
        for v in sorted(literals(ROOT / "lib/source" / f) - named):
            print(f"not in the dictionary: {x(v)} in lib/source/{f}")
            bad += 1
    for f, text in (("Colors.mc", colors_mc()), ("Neon.mc", neon_mc())):
        p = ROOT / "lib/source" / f
        if not p.exists() or p.read_text() != text:
            print(f"lib/source/{f} differs from its generator")
            bad += 1
    print(f"colours: {len(C)} named, {bad} problems")
    return bad


def apps():
    named = set(C.values())
    total = 0
    for p in sorted((ROOT / "apps").glob("*/source/*.mc")):
        loose = sorted(literals(p) - named - {0x000000})
        if loose:
            total += len(loose)
            print(f"{p.relative_to(ROOT)}: " + " ".join(x(v) for v in loose))
    print(f"{total} colour uses in the apps aren't named yet")


if __name__ == "__main__":
    if "--check" in sys.argv:
        sys.exit(1 if check() else 0)
    if "--apps" in sys.argv:
        apps()
        sys.exit(0)
    (ROOT / "lib/source/Colors.mc").write_text(colors_mc())
    (ROOT / "lib/source/Neon.mc").write_text(neon_mc())
    print(f"Colors.mc: {len(C)} colours; Neon.mc: {len(TUBES)} tubes, {len(NEON_SETS)} sets")
