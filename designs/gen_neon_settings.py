#!/usr/bin/env python3
"""Generate a neon face's settings resources (Sign, Edge, Noir), the ones
Lib.Neon and Lib.Look read:

- Look (first): your tubes, high visibility in red, blue or green, low
  light, or a new set each day; holding the time on the watch steps
  through the same six
- Hours, Minutes, Detail: a tube each, from the sign shop's chart
  (designs/colors.py, TUBES). No free colour picker and no watch face
  editor colours: every choice stays a colour neon can make

    python3 -I designs/gen_neon_settings.py sign|edge|noir

Writes resources/settings/properties.xml and settings.xml, and
resources/strings/strings.xml whole; the face's own strings go in FACES.
Regenerate rather than edit the output.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))                                   # run with -I
from colors import NEON_SETS, TUBES                             # noqa: E402

ROOT = HERE.parent
HEAD = '<{0} xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="https://developer.garmin.com/downloads/connect-iq/resources.xsd">\n'
NOTE = "    <!-- Generated by designs/gen_neon_settings.py; regenerate, don't edit. -->\n"
# Lib.Look's modes in its ORDER, with their numbers (new looks take new numbers)
LOOKS = [("Yours", "Your tubes below", 0), ("Bright", "High visibility, red", 1),
         ("BrightBlue", "High visibility, blue", 4), ("BrightGreen", "High visibility, green", 5),
         ("Low", "Low light", 2), ("Daily", "A new set each day", 3)]

# name, what each tube lights, and any strings of the face's own
FACES = {
    "sign": dict(name="Neon Sign", hours="The hours", minutes="The minutes", detail="The date", strings={}),
    "edge": dict(name="Neon Edge", hours="Edges facing the upper left", minutes="Edges facing the lower right",
                 detail="The date", strings={}),
    "noir": dict(name="Neon Noir", hours="The hour hand", minutes="The minute hand",
                 detail="The markers and the date", strings={}),
}


def key(s):
    return "".join(w.capitalize() for w in s.replace("_", " ").split())


def main(face):
    f = FACES[face]
    res = ROOT / "apps" / face / "resources"
    tubes = list(TUBES)
    first = next(iter(NEON_SETS.values()))
    parts = (("Hours", f["hours"]), ("Minutes", f["minutes"]), ("Detail", f["detail"]))

    p = HEAD.format("properties") + NOTE
    p += f"    <!-- Lib.Look: {', '.join(f'{i} {n}' for _, n, i in sorted(LOOKS, key=lambda look: look[2]))} -->\n"
    p += '    <property id="Look" type="number">0</property>\n'
    p += f"    <!-- Lib.Neon.TUBES: {', '.join(f'{i} {TUBES[n][3]}' for i, n in enumerate(tubes))} -->\n"
    for (prop, what), tube in zip(parts, first):
        p += f'    <!-- {what} -->\n    <property id="{prop}" type="number">{tubes.index(tube)}</property>\n'
    p += "</properties>\n"
    (res / "settings").mkdir(parents=True, exist_ok=True)
    (res / "settings/properties.xml").write_text(p)

    s = HEAD.format("settings") + NOTE
    s += '    <setting propertyKey="@Properties.Look" title="@Strings.LookTitle" prompt="@Strings.LookPrompt">\n'
    s += '        <settingConfig type="list">\n'
    s += "".join(f'            <listEntry value="{i}">@Strings.Look{k}</listEntry>\n' for k, _, i in LOOKS)
    s += "        </settingConfig>\n    </setting>\n"
    for prop, _ in parts:
        s += f'    <setting propertyKey="@Properties.{prop}" title="@Strings.{prop}Title">\n        <settingConfig type="list">\n'
        s += "".join(f'            <listEntry value="{i}">@Strings.Tube{key(n)}</listEntry>\n' for i, n in enumerate(tubes))
        s += "        </settingConfig>\n    </setting>\n"
    s += "</settings>\n"
    (res / "settings/settings.xml").write_text(s)

    st = HEAD.format("strings") + NOTE
    st += f'    <string id="AppName">{f["name"]}</string>\n'
    st += '    <string id="LookTitle">Look</string>\n'
    st += '    <string id="LookPrompt">Or press and hold the time on the watch to step through the looks.</string>\n'
    st += "".join(f'    <string id="Look{k}">{n}</string>\n' for k, n, _ in LOOKS)
    st += "".join(f'    <string id="{prop}Title">{what}</string>\n' for prop, what in parts)
    st += "".join(f'    <string id="Tube{key(n)}">{TUBES[n][3]}</string>\n' for n in tubes)
    st += "".join(f'    <string id="{k}">{v}</string>\n' for k, v in f["strings"].items())
    st += "</strings>\n"
    (res / "strings").mkdir(parents=True, exist_ok=True)
    (res / "strings/strings.xml").write_text(st)
    print(f"{face}: {len(tubes)} tubes, {len(LOOKS)} looks")


if __name__ == "__main__":
    main(sys.argv[1])
