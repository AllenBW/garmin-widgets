#!/usr/bin/env python3
"""Generate the Sign face's tubes (design #57) from its preview, for every
screen width the apps are built for:

- apps/sign/resources-round-<w>x<w>/drawables/: a PNG per numeral
  (d0..d9) and per letter of the date and the looks' names (s_a..s_z,
  s_0..s_9, s_hyphen), two each: its halo (the glyph's box with room
  round it) and its core, grey masks kept as the alpha of a white
  picture. `drawBitmap2` tints the halo with the tube's
  colour and the core with the colour washed toward white, so every tube
  of Lib.Neon works with one set of pictures. Kept as PNG with no palette
  (`packingFormat="png" automaticPalette="false"`): the tint refuses a
  paletted picture, and the halo needs all eight bits of its alpha.
  The watches that can't unpack a PNG (the Forerunner 165, 165 Music and
  70: no "png" among imageFormats in their compiler.json) are left off
  Sign's device list (scripts/devices.py): in the default packing the
  tint works but the halo's faintest levels are lost.
- apps/sign/resources-round-<w>x<w>/fonts/: the standby numerals, thin
  tubes with no halo, as a BMFont (`drawText` colours it; a font keeps
  two bits of grey, enough for a thin line and no more, which is why the
  halos are pictures).
- apps/sign/source/Layout.mc: the whole-pixel sizes the view places them
  by, per width, and the resources' ids.

    python3 -I designs/gen_sign.py

Pillow only. Regenerate rather than edit the output.
"""
import sys
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))                                   # run with -I
import preview_sign as ps  # noqa: E402

APP = HERE.parent / "apps" / "sign"
HEAD = '<{0} xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="https://developer.garmin.com/downloads/connect-iq/resources.xsd">\n'
NOTE = "    <!-- Generated by designs/gen_sign.py; regenerate, don't edit. -->\n"
DIGITS = "0123456789"


def name(ch):
    return ps.NAMES.get(ch, ch)


def picture(mask):
    """A grey mask as the alpha of a white picture."""
    im = Image.new("RGBA", mask.size, (255, 255, 255, 0))
    im.putalpha(mask)
    return im


def write_width(w):
    s = ps.sprites(w)
    res = APP / f"resources-round-{w}x{w}"
    folder = res / "drawables"
    folder.mkdir(parents=True, exist_ok=True)
    xml = HEAD.format("drawables") + NOTE
    xml += "    <!-- The numerals and the letters: a halo and a core each, grey masks the view tints -->\n"
    for small, chars, prefix in ((False, DIGITS, "d"), (True, ps.SMALL_CHARS, "s_")):
        for ch in chars:
            halo, core = s.lit(ch, small)
            assert halo.getextrema()[1] > 15 and core.getextrema()[1] >= 200, (w, ch, core.getextrema())   # a line the watch shows
            for part, mask in (("halo", halo), ("core", core)):
                file = f"{prefix}{name(ch).lower()}_{part}.png"
                picture(mask).save(folder / file, optimize=True)
                rid = ("D" if not small else "S") + part.title() + name(ch)
                xml += f'    <bitmap id="{rid}" filename="{file}" packingFormat="png" automaticPalette="false"/>\n'
    xml += "</drawables>\n"
    (folder / "tubes.xml").write_text(xml)
    # the standby numerals: a row of tight cells
    folder = res / "fonts"
    folder.mkdir(parents=True, exist_ok=True)
    masks = [s.standby(ch) for ch in DIGITS]
    height = masks[0].size[1]
    sheet = Image.new("L", (sum(m.size[0] + 2 for m in masks) + 2, height + 4), 0)
    fnt = []
    x = 2
    for ch, m in zip(DIGITS, masks):
        assert m.getextrema()[1] >= 200, (w, ch, m.getextrema())
        sheet.paste(m, (x, 2))
        fnt.append("char id=%d x=%d y=2 width=%d height=%d xoffset=0 yoffset=0 xadvance=%d page=0 chnl=15"
                   % (ord(ch), x, m.size[0], height, m.size[0]))
        x += m.size[0] + 2
    sheet.save(folder / "thin.png", optimize=True)
    head = ['info face="sign_thin" size=%d bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=1 aa=1 padding=0,0,0,0 spacing=2,2 outline=0' % height,
            "common lineHeight=%d base=%d scaleW=%d scaleH=%d pages=1 packed=0 alphaChnl=1 redChnl=4 greenChnl=4 blueChnl=4"
            % (height, height, sheet.size[0], sheet.size[1]),
            'page id=0 file="thin.png"', "chars count=10"]
    (folder / "thin.fnt").write_text("\n".join(head + fnt) + "\n")
    xml = HEAD.format("fonts") + NOTE
    xml += "    <!-- The standby numerals: thin tubes, no halo -->\n"
    xml += '    <font id="Thin" filename="thin.fnt" filter="0123456789" antialias="true"/>\n</fonts>\n'
    (folder / "fonts.xml").write_text(xml)
    worst = max(ps.lit_share(ps.face(w, hh, "08", [], ps.tubes()[0], True)) for hh in ("08", "20", "00"))
    print(f"{w}: numerals {s.h} px, letters {s.sh} px, standby at most {worst:.1%} lit")
    return s


def mc(values):
    return "[" + ", ".join(str(v) for v in values) + "]"


def write_layout(all_sprites):
    rows = lambda fn: ",\n            ".join(mc(fn(s)) + " as Array<Number>" for s in all_sprites)   # noqa: E731
    small = ps.SMALL_CHARS
    out = f"""// Generated by designs/gen_sign.py from designs/preview_sign.py; regenerate, don't edit.
import Toybox.Lang;

// Sign's whole-pixel sizes, a row per screen width, and its pictures: for
// each numeral and letter its halo (the glyph's box with PAD round it) and
// its core (the box with its margin round it).
module Layout {{

    const WIDTHS = {mc(ps.WIDTHS)} as Array<Number>;

    // Per width: the numerals' height, the gap between them, the halo's
    // room, the core's margin, the standby tube's margin; the letters'
    // height, gap, space, line gap, halo room and core margin; then the
    // time's centre line and its rows' tops, the date's centre, and the
    // standby shift's step (Lib.Aod.offset)
    enum {{ H, GAP, PAD, MARGIN, THIN_MARGIN, SMALL_H, SMALL_GAP, SPACE, LINE, SMALL_PAD, SMALL_MARGIN,
           X, Y_HOURS, Y_MINUTES, DATE_X, DATE_Y, AOD_STEP }}
    const SIZES = [
            {rows(lambda s: [s.h, s.gap, s.pad, s.m, s.tm, s.sh, s.sgap, s.space, s.line, s.spad, s.sm] + ps.places(s.w))}
        ] as Array<Array<Number>>;

    // The numerals' box widths, 0 to 9, and the room each asks for on its
    // left and right beside another numeral (the one's flag, the seven's bar)
    const ADVANCE = [
            {rows(lambda s: [s.adv(c) for c in DIGITS])}
        ] as Array<Array<Number>>;
    const LEFT = [
            {rows(lambda s: [s.bearings(c)[0] for c in DIGITS])}
        ] as Array<Array<Number>>;
    const RIGHT = [
            {rows(lambda s: [s.bearings(c)[1] for c in DIGITS])}
        ] as Array<Array<Number>>;

    // The letters, in the order of SMALL
    const LETTERS = "{small}";
    const SMALL_ADVANCE = [
            {rows(lambda s: [s.adv(c, True) for c in small])}
        ] as Array<Array<Number>>;

    // The pictures: the numerals' halos and cores, 0 to 9, and the letters'
    function halos() as Array<ResourceId> {{
        return [{", ".join("Rez.Drawables.DHalo" + c for c in DIGITS)}] as Array<ResourceId>;
    }}

    function cores() as Array<ResourceId> {{
        return [{", ".join("Rez.Drawables.DCore" + c for c in DIGITS)}] as Array<ResourceId>;
    }}

    function smallHalos() as Array<ResourceId> {{
        return [{", ".join("Rez.Drawables.SHalo" + name(c) for c in small)}] as Array<ResourceId>;
    }}

    function smallCores() as Array<ResourceId> {{
        return [{", ".join("Rez.Drawables.SCore" + name(c) for c in small)}] as Array<ResourceId>;
    }}

    // The row of the tables for a screen `width` wide: its own, or the
    // widest one that fits
    function row(width as Number) as Number {{
        var best = 0;
        for (var i = 0; i < WIDTHS.size(); i++) {{
            if (WIDTHS[i] <= width) {{
                best = i;
            }}
        }}
        return best;
    }}
}}
"""
    (APP / "source").mkdir(parents=True, exist_ok=True)
    (APP / "source" / "Layout.mc").write_text(out)


def main():
    write_layout([write_width(w) for w in ps.WIDTHS])


if __name__ == "__main__":
    main()
