#!/usr/bin/env python3
"""Generate the settings of the faces whose settings are their own lists
(not gen_face_settings.py's accent and data colours, nor the neon faces'
tubes) from one description each, so the phone app's settings list
(resources/settings/*.xml), the watch face editor
(resources/configs/watchface.xml) and the face's settings menu on the
watch (source/Choices.mc, read by Lib.WatchMenu from getSettingsView)
always offer the same choices:

- Look (first on the phone and in the menu): your settings, high
  visibility in orange, blue or green, low light or a new look each day
  (Lib.Look); holding the time on the watch steps through the same six,
  and the editor has no place for it
- then the face's own settings, in the phone list's order. Up to three of
  them are in the editor too, its styles, its accent colours and its data
  colours, each offering exactly that setting's choices; a colour list
  needs a swatch for every choice, and the editor hands back the swatch,
  which Choices.editor() turns into the setting's value

Choices.editor() is the editor's choices as the properties they stand for,
or nothing once the phone app (or the watch's menu, which writes the same
properties) was changed since the editor: the app calls
Lib.Config.changedOnPhone from onSettingsChanged and the delegate
Lib.Config.changedInEditor from onWatchFaceConfigEdited, so whichever was
changed last wins.

    python3 designs/gen_own_settings.py field|rings|strata|readiness|forage

Regenerate rather than edit the output; resources/strings/strings.xml is
written whole too, so a face's strings go in FACES below.
"""
