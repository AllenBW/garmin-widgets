def editor_lists(f):
    """{"style"|"accent"|"data": the setting} for the editor's lists"""
    out = {}
    for s in f["settings"]:
        if s["editor"]:
            assert s["editor"] not in out, f"two settings for the editor's {s['editor']}"
            out[s["editor"]] = s
    return out


def upper(prop):
    """AccentColor -> ACCENT_COLOR"""
    return "".join(("_" + c if c.isupper() and i else c.upper()) for i, c in enumerate(prop))


def words(e, editor=False):
    return e[4] if editor and len(e) > 4 else e[2]


def main(face):
    f = FACES[face]
    res = ROOT / "apps" / face / "resources"
    lists = editor_lists(f)
    # string ids: a setting's title, its entries (shared by settings with the same `strings`)
    strings = {"AppName": f["name"], "LookTitle": "Look",
               "LookPrompt": "Or press and hold the time on the watch to step through the looks."}
    strings.update({"Look" + k: (f["yours"] if k == "Yours" else n) for k, n, _ in LOOKS})
    for s in f["settings"]:
        strings[s["prop"] + "Title"] = s["title"]
        for e in s.get("entries", []):
            strings[s["strings"] + e[1]] = e[2]
            if len(e) > 4 and e[4] != e[2]:
                strings[s["strings"] + e[1] + "Short"] = e[4]
    if any(s["kind"] == "boolean" for s in f["settings"]):
        strings.update({"On": "On", "Off": "Off"})

    def sid(s, e, editor=False):
        return s["strings"] + e[1] + ("Short" if editor and len(e) > 4 and e[4] != e[2] else "")

    # The editor
    cfg = HEAD.format("resources") + NOTE
    cfg += f"""    <!-- The fēnix 8's own watch face editor (Watch Face > {f['name']} > Customize): {f['editor_note']}.
         The phone app's settings list and the watch's own settings menu have the same
         choices (resources/settings, Choices); whichever was changed last wins (Choices.editor). -->
    <watchface-config>
"""
    if "style" in lists:
        s = lists["style"]
        cfg += "        <styles>\n"
        for i, e in enumerate(s["entries"]):
            d = ' default="true"' if e[0] == s["default"] else ""
            cfg += f'            <style id="{i}" label="@Strings.{sid(s, e, True)}"{d}/>\n'
        cfg += "        </styles>\n"
    for part, tag in (("accent", "accentColors"), ("data", "dataColors")):
        if part in lists:
            s = lists[part]
            cfg += f"        <{tag}>\n"
            for e in s["entries"]:
                d = ' default="true"' if e[0] == s["default"] else ""
                cfg += f'            <color label="@Strings.{sid(s, e, True)}"{d}>{e[3]}</color>\n'
            cfg += f"        </{tag}>\n"
    if f.get("complications"):
        cfg += "        <data>\n"
        for i, (types, default) in enumerate(f["complications"]):
            cfg += f'            <complication id="{i + 1}">\n'
            for t in types:
                d = ' default="true"' if t == default else ""
                cfg += f"                <type{d}>Complications.COMPLICATION_TYPE_{t}</type>\n"
            cfg += "            </complication>\n"
        cfg += "        </data>\n"
    cfg += "    </watchface-config>\n</resources>\n"
    (res / "configs").mkdir(parents=True, exist_ok=True)
    (res / "configs/watchface.xml").write_text(cfg)

    # The phone app's properties and list
    p = HEAD.format("properties") + NOTE
    p += f"    <!-- Lib.Look: {', '.join(f'{i} {n}' for _, n, i in sorted(LOOKS, key=lambda look: look[2]))} -->\n"
    p += '    <property id="Look" type="number">0</property>\n'
    for s in f["settings"]:
        if s["comment"]:
            p += f"    <!-- {s['comment']} -->\n"
        value = ("true" if s["default"] else "false") if s["kind"] == "boolean" else s["default"]
        p += f'    <property id="{s["prop"]}" type="{"boolean" if s["kind"] == "boolean" else "number"}">{value}</property>\n'
    p += "</properties>\n"
    (res / "settings").mkdir(parents=True, exist_ok=True)
    (res / "settings/properties.xml").write_text(p)

    st = HEAD.format("settings") + NOTE
    st += '    <setting propertyKey="@Properties.Look" title="@Strings.LookTitle" prompt="@Strings.LookPrompt">\n'
    st += '        <settingConfig type="list">\n'
    st += "".join(f'            <listEntry value="{i}">@Strings.Look{k}</listEntry>\n' for k, _, i in LOOKS)
    st += "        </settingConfig>\n    </setting>\n"
    for s in f["settings"]:
        st += f'    <setting propertyKey="@Properties.{s["prop"]}" title="@Strings.{s["prop"]}Title">\n'
        if s["kind"] == "boolean":
            st += '        <settingConfig type="boolean"/>\n    </setting>\n'
            continue
        st += '        <settingConfig type="list">\n'
        st += "".join(f'            <listEntry value="{e[0]}">@Strings.{sid(s, e)}</listEntry>\n' for e in s["entries"])
        st += "        </settingConfig>\n    </setting>\n"
    st += "</settings>\n"
    (res / "settings/settings.xml").write_text(st)

    x = HEAD.format("strings") + NOTE
    x += "".join(f'    <string id="{k}">{v}</string>\n' for k, v in strings.items())
    x += "</strings>\n"
    (res / "strings").mkdir(parents=True, exist_ok=True)
    (res / "strings/strings.xml").write_text(x)

    (ROOT / "apps" / face / "source/Choices.mc").write_text(choices(f, lists, sid))
    print(f"{face}: {len(f['settings'])} settings, the editor's {', '.join(lists) or 'nothing'}")


def choices(f, lists, sid):
    ids = lambda names: ", ".join(f"Rez.Strings.{n}" for n in names)
    shared, lines = {}, []
    # entries shared by several settings (the slots) are loaded once
    for s in f["settings"]:
        if s["kind"] == "list":
            shared.setdefault(s["strings"] + ":" + ",".join(str(e[0]) for e in s["entries"]), []).append(s)
    names = {}
    pre = ""
    for k, group in shared.items():
        if len(group) > 1:
            s = group[0]
            var = s["strings"][0].lower() + s["strings"][1:] + "s"
            pre += f"        var {var} = strings([{ids(sid(s, e) for e in s['entries'])}] as Array<ResourceId>);\n"
            pre += f"        var {var}Values = [{', '.join(str(e[0]) for e in s['entries'])}] as Array<Number>;\n"
            for g in group:
                names[g["prop"]] = (var, var + "Values")
    lines.append(f"            [load(Rez.Strings.LookTitle), null, strings([{ids('Look' + k for k, _, _ in LOOKS)}] as Array<ResourceId>),\n"
                 f"             [{', '.join(str(i) for _, _, i in LOOKS)}] as Array<Number>]")
    for s in f["settings"]:
        if s["kind"] == "boolean":
            lines.append(f'            [load(Rez.Strings.{s["prop"]}Title), "{s["prop"]}", strings([Rez.Strings.On, Rez.Strings.Off] as Array<ResourceId>),\n'
                         "             [true, false] as Array<Boolean>]")
        elif s["prop"] in names:
            a, b = names[s["prop"]]
            lines.append(f'            [load(Rez.Strings.{s["prop"]}Title), "{s["prop"]}", {a}, {b}]')
        else:
            lines.append(f'            [load(Rez.Strings.{s["prop"]}Title), "{s["prop"]}", strings([{ids(sid(s, e) for e in s["entries"])}] as Array<ResourceId>),\n'
                         f"             [{', '.join(str(e[0]) for e in s['entries'])}] as Array<Number>]")

    ed = ""
    if "style" in lists:
        s = lists["style"]
        n = len(s["entries"])
        ed += f"""        var style = config.styleId;
        if (style != null && style >= 0 && style < {n}) {{
            out["{s['prop']}"] = ([{', '.join(str(e[0]) for e in s['entries'])}] as Array<Number>)[style];
        }}
"""
    for part, field in (("accent", "accentColor"), ("data", "complicationColor")):
        if part in lists:
            s = lists[part]
            ed += f"""        var {part} = config.{field};
        if ({part} != null && {part}.color != null) {{
            pick(out, "{s['prop']}", {part}.color as Number, {upper(s['prop'])}, [{', '.join(str(e[0]) for e in s['entries'])}] as Array<Number>);
        }}
"""
    ed = "".join("        " + line + "\n" if line else "\n" for line in ed.splitlines())
    plain = [s for s in f["settings"] if s["editor"] is None]
    consts = ""
    for part in ("accent", "data"):
        if part in lists:
            s = lists[part]
            consts += f"""
    // {s['title']}: the editor's swatches, a choice each, in the phone list's order
    const {upper(s['prop'])} = [{', '.join(e[3] for e in s['entries'])}] as Array<Number>;
"""
    what = {"style": "its style", "accent": "its accent colour", "data": "its data colour"}
    said = ", ".join(f"{what[p]} {lists[p]['prop']}" for p in ("style", "accent", "data") if p in lists)
    if plain:
        said += "; " + ", ".join(s["prop"] for s in plain) + " are the phone's and the menu's alone"
    said = "\n".join("    // " + line for line in textwrap.wrap(said, 72))
    return f"""// Generated by designs/gen_own_settings.py; regenerate, don't edit.
import Toybox.Application;
import Toybox.Application.WatchFaceConfig;
import Toybox.Lang;
import Toybox.WatchUi;

// {f['name']}'s settings on the watch: the phone app's list as the face's own
// menu (Lib.WatchMenu, from getSettingsView), the same choices writing the
// same properties; and the watch face editor's lists read as the
// properties they stand for
module Choices {{
{consts}
    function entries() as Array<Lib.WatchMenu.Entry> {{
{pre}        return [
{(","+chr(10)).join(lines)}
        ] as Array<Lib.WatchMenu.Entry>;
    }}

    function load(id as ResourceId) as String {{
        return WatchUi.loadResource(id) as String;
    }}

    function strings(ids as Array<ResourceId>) as Array<String> {{
        var out = [] as Array<String>;
        for (var i = 0; i < ids.size(); i++) {{
            out.add(load(ids[i]));
        }}
        return out;
    }}

    // Whether the fēnix 8's watch face editor was changed since the phone
    // app or this menu (until either is, the editor's, which starts at the
    // phone list's defaults); a watch without the editor has the phone's
    function editorWins() as Boolean {{
        return (Application has :WatchFaceConfig) && !Lib.Config.PHONE.equals(Application.Storage.getValue(Lib.Config.SOURCE));
    }}

    // The editor's choices as {{property => value}} when it wins, else none:
{said}
    function editor() as Dictionary<String, Number> {{
        var out = {{}} as Dictionary<String, Number>;
        if (Application has :WatchFaceConfig) {{
            var config = editorWins() ? WatchFaceConfig.getSettings(null) : null;
            if (config != null) {{
{ed}            }}
        }}
        return out;
    }}
{'''
    // An editor colour, its swatch turned into the setting's value
    function pick(out as Dictionary<String, Number>, key as String, color as Number,
                  colors as Array<Number>, values as Array<Number>) as Void {
        var i = colors.indexOf(color);
        if (i >= 0) {
            out[key] = values[i];
        }
    }
''' if ("accent" in lists or "data" in lists) else ""}
    // A number setting as it stands: the editor's (`editor`, from editor())
    // or the phone's, `fallback` when unset or not a number
    function number(editor as Dictionary<String, Number>, key as String, fallback as Number) as Number {{
        var value = editor.hasKey(key) ? editor[key] : Application.Properties.getValue(key);
        return (value instanceof Number) ? value : fallback;
    }}
}}
"""


if __name__ == "__main__":
    for name in sys.argv[1:] or FACES:
        main(name)
