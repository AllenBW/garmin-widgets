def S(prop, title, entries, default, comment, editor=None, strings=None, prompt=None):
    """A list setting: entries are (value, key, the phone's words[, swatch[, the editor's words]])"""
    return dict(prop=prop, title=title, entries=entries, default=default, comment=comment,
                editor=editor, strings=strings or prop, prompt=prompt, kind="list")


def B(prop, title, default, comment):
    """A switch"""
    return dict(prop=prop, title=title, default=default, comment=comment, kind="boolean", editor=None)


